async function main() {
    for (const site of sites) {
        await prisma.siteDataConfig.upsert({
            where: { domain: site.domain },
            update: {
                retailerName: site.retailerName,
                siteMapUrl: Array.isArray(site.siteMapUrl) ? site.siteMapUrl : site.siteMapUrl ? [site.siteMapUrl] : undefined,
                ecommercePlatform: site.ecommercePlatform
            },
            create: {
                domain: site.domain,
                retailerName: site.retailerName,
                siteMapUrl: Array.isArray(site.siteMapUrl) ? site.siteMapUrl : site.siteMapUrl ? [site.siteMapUrl] : undefined,
                ecommercePlatform: site.ecommercePlatform
            }
        });

        console.log(`✅ Upserted: ${site.domain}`);
    }
}

main()
    .catch((err) => {
        console.error('❌ Error upserting site configs:', err);
        process.exit(1);
    })
    .finally(() => prisma.$disconnect());
